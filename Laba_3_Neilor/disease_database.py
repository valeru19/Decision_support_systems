def get_all_symptoms():
    """Получить все уникальные симптомы"""
    symptoms = set()
    for disease in DISEASES_DATABASE.values():
        symptoms.update(disease["symptoms"].keys())
    return list(symptoms)

def get_disease_symptoms(disease_name):
    """Получить симптомы для конкретного заболевания"""
    return DISEASES_DATABASE.get(disease_name, {}).get("symptoms", {})

def get_symptom_weight(disease_name, symptom_name):
    """Получить вес симптома для заболевания"""
    return DISEASES_DATABASE.get(disease_name, {}).get("symptoms", {}).get(symptom_name, {}).get("weight", 0)

def get_symptom_specificity(disease_name, symptom_name):
    """Получить специфичность симптома для заболевания"""
    return DISEASES_DATABASE.get(disease_name, {}).get("symptoms", {}).get(symptom_name, {}).get("specificity", 0)